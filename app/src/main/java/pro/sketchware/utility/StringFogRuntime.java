package pro.sketchware.utility;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;

/**
 * Generates the StringFog runtime used by compiled user projects.
 *
 * <p>StringFog core 5.2.0's Base64 writer passes both the encrypted value and the key as Base64
 * strings to {@code decrypt(String, String)}. The runtime bundled in {@code stringfog.zip} is an
 * older implementation that decodes only the value and treats the key as a plain string, which
 * makes every decrypted string garbage. Generating a matching runtime avoids that mismatch.
 */
public final class StringFogRuntime {

    public static final String RELATIVE_PATH = "com/github/megatronking/stringfog/xor/StringFogImpl.java";

    private static final String SOURCE = """
            package com.github.megatronking.stringfog.xor;

            import android.util.Base64;

            import java.nio.charset.StandardCharsets;

            /**
             * Runtime counterpart of the StringFog 5.2.0 Base64 instruction writer.
             * Generated by Sketchware Pro; do not edit.
             */
            public final class StringFogImpl {
                private StringFogImpl() {
                }

                public static String decrypt(String value, String key) {
                    byte[] data = Base64.decode(value, Base64.DEFAULT);
                    byte[] secret = Base64.decode(key, Base64.DEFAULT);
                    for (int i = 0; i < data.length; i++) {
                        data[i] = (byte) (data[i] ^ secret[i % secret.length]);
                    }
                    return new String(data, StandardCharsets.UTF_8);
                }
            }
            """;

    private StringFogRuntime() {
    }

    /**
     * Writes the runtime class into the generated project's Java source tree so ECJ compiles it.
     */
    public static void writeToJavaSourceDir(File javaFilesPath) throws IOException {
        File target = new File(javaFilesPath, RELATIVE_PATH);
        File parent = target.getParentFile();
        if (parent != null) {
            Files.createDirectories(parent.toPath());
        }
        Files.writeString(target.toPath(), SOURCE, StandardCharsets.UTF_8);
    }
}
